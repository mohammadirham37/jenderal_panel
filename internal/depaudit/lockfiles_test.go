func TestRegistryVersionSkipsNonRegistry(t *testing.T) {
	for _, v := range []string{"", "dev-main", "dev-feature/x", "git+https://github.com/a/b.git", "file:../x", "workspace:*", "link:../y", "https://example.com/a.tgz", "1.x-dev"} {
		if got, ok := registryVersion(v); ok {
			t.Errorf("registryVersion(%q) = %q, want skipped", v, got)
		}
	}
	if got, ok := registryVersion("v2.1.0"); !ok || got != "2.1.0" {
		t.Errorf("registryVersion(v2.1.0) = %q, %v", got, ok)
	}
	if got, ok := registryVersion("1.0.0-beta.2"); !ok || got != "1.0.0-beta.2" {
		t.Errorf("registryVersion(1.0.0-beta.2) = %q, %v", got, ok)
	}
}

func TestDedupeKeepsProdOverDev(t *testing.T) {
	deps := dedupe([]Dependency{
		{Ecosystem: EcosystemNPM, Name: "a", Version: "1.0.0", Dev: true},
		{Ecosystem: EcosystemNPM, Name: "a", Version: "1.0.0"},
		{Ecosystem: EcosystemNPM, Name: "a", Version: "2.0.0", Dev: true},
	})
	assertDeps(t, deps, "npm:a@1.0.0", "npm:a@2.0.0 dev")
}

func TestParseLockfileRejectsUnknownAndBroken(t *testing.T) {
	if _, err := ParseLockfile("Gemfile.lock", nil); err == nil {
		t.Error("unknown lockfile must be rejected")
	}
	if _, err := ParseLockfile("composer.lock", []byte("{not json")); err == nil {
		t.Error("broken JSON must be an error")
	}
}
