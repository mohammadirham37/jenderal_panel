package depaudit

import (
	"sort"
	"strings"
	"testing"
)

func depStrings(deps []Dependency) string {
	out := make([]string, 0, len(deps))
	for _, d := range deps {
		s := d.Ecosystem + ":" + d.Name + "@" + d.Version
		if d.Dev {
			s += " dev"
		}
		out = append(out, s)
	}
	sort.Strings(out)
	return strings.Join(out, "\n")
}

func assertDeps(t *testing.T, got []Dependency, want ...string) {
	t.Helper()
	sort.Strings(want)
	if g := depStrings(got); g != strings.Join(want, "\n") {
		t.Errorf("deps:\n%s\nwant:\n%s", g, strings.Join(want, "\n"))
	}
}

func TestParseComposerLock(t *testing.T) {
	data := `{
  "packages": [
    {"name": "laravel/framework", "version": "v11.9.2"},
    {"name": "guzzlehttp/guzzle", "version": "7.8.1"},
    {"name": "acme/private", "version": "dev-main"}
  ],
  "packages-dev": [
    {"name": "phpunit/phpunit", "version": "10.5.20"}
  ]
}`
	deps, err := ParseLockfile("composer.lock", []byte(data))
	if err != nil {
		t.Fatal(err)
	}
	assertDeps(t, deps,
		"Packagist:laravel/framework@11.9.2",
		"Packagist:guzzlehttp/guzzle@7.8.1",
		"Packagist:phpunit/phpunit@10.5.20 dev")
	for _, d := range deps {
		if d.Lockfile != "composer.lock" {
			t.Errorf("lockfile = %q", d.Lockfile)
		}
	}
}

